/**
 * Normalize a host locale value (`zh-CN`, `pt-BR`, `en_US`, …) to a supported id.
 * @param {unknown} value
 * @returns {string} one of SUPPORTED_LOCALES; `en` when unknown.
 */
export function normalizeLocale(value) {
  if (typeof value !== 'string') return 'en';
  const primary = value.trim().toLowerCase().replace(/_/gu, '-').split('-')[0];
  return SUPPORTED_LOCALES.includes(primary) ? primary : 'en';
}

/**
 * Translate a command message for one locale, with `en` and then the key itself
 * as fallbacks. Unknown placeholders are left untouched.
 * @param {string} locale - normalized locale id.
 * @param {keyof typeof COMMAND_DICTS.en} key
 * @param {Record<string, string | number>} [params]
 * @returns {string}
 */
export function translateCommand(locale, key, params) {
  const id = normalizeLocale(locale);
  const template = COMMAND_DICTS[id]?.[key] ?? COMMAND_DICTS.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/gu, (match, name) => (name in params ? String(params[name]) : match));
}
