/**
 * Wrap src/core.js + src/client.js into the ESM-less browser bundle DSH's
 * client module loader expects (`window.__ModuleLoader__.load({...})`).
 *
 * The sources stay plain ESM for unit tests; this script only strips the
 * module syntax (no bundler, no dependencies).
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'lib', 'client.js');
const PLUGIN_ID = 'dsh-nonead-prompt-recall';

/**
 * Strip imports and `export` keywords from one source file.
 * @param {string} source
 * @returns {string}
 */
function toFactoryBody(source) {
  return source
    .split(/\r?\n/u)
    .map((line) => {
      if (/^\s*import\s/u.test(line)) return '';
      return line.replace(/^export\s+/u, '');
    })
    .join('\n')
    .trim();
}

const core = toFactoryBody(await readFile(join(ROOT, 'src', 'core.js'), 'utf8'));
const client = toFactoryBody(await readFile(join(ROOT, 'src', 'client.js'), 'utf8'));

const bundle = `/* dsh-nonead-prompt-recall client bundle — generated by scripts/build-client.mjs.
 * Edit src/core.js and src/client.js, then run: node scripts/build-client.mjs
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PLUGIN_ID)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;

${core}

${client}

    module.exports = { name, inject, apply };
    return module.exports;
  }
});
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, bundle, 'utf8');
console.log(`built ${OUT} (${bundle.length} bytes)`);
