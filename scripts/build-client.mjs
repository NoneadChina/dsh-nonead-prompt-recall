/**
 * Wrap src/protocol.js + src/i18n.js + src/core.js + src/optimize.js +
 * src/settings.js + src/client.js into the ESM-less browser bundle DSH's client
 * module loader expects (`window.__ModuleLoader__.load({...})`).
 *
 * The sources stay plain ESM for unit tests; this script only strips the
 * module syntax (no bundler, no dependencies).
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'lib', 'client.js');
const PLUGIN_ID = 'dsh-nonead-prompt-recall';

/**
 * Strip imports and `export` keywords from one source file.
 * @param {string} source
 * @returns {string}
 */
function toFactoryBody(source) {
  return source
    .split(/\r?\n/u)
    .map((line) => {
      if (/^\s*import\s/u.test(line)) return '';
      return line.replace(/^export\s+/u, '');
    })
    .join('\n')
    .trim();
}

/**
 * Path the host reports for one stylesheet, keyed by the source constant that
 * holds its text. The paths are stable identifiers inside the bundle, not
 * files on disk: the renderer only uses them for de-duplication.
 */
const STYLE_SOURCES = [
  ['src/optimize-button.css', 'src/optimize-button.js', 'OPT_CSS'],
  ['src/settings.css', 'src/settings.js', 'CSS'],
  ['src/settings-polish.css', 'src/settings.js', 'POLISH_CSS'],
];

/**
 * Read one ``const NAME = `...`;`` CSS block out of a source file, verbatim.
 *
 * The sources keep the styles inline so the older manual-injection path can use
 * them straight from the same constants; this only lifts a copy for the bundle
 * metadata, so a drift here must fail the build rather than ship an empty sheet.
 * @param {string} source
 * @param {string} name
 * @param {string} file
 * @returns {string}
 */
function cssConstant(source, name, file) {
  const match = source.match(new RegExp('const ' + name + ' = `([\\s\\S]*?)`;', 'u'));
  if (match === null) {
    console.error(`build-client: ${name} not found in ${file}`);
    process.exit(1);
  }
  return match[1];
}

const protocol = toFactoryBody(await readFile(join(ROOT, 'src', 'protocol.js'), 'utf8'));
const i18nOptimize = toFactoryBody(await readFile(join(ROOT, 'src', 'i18n-optimize.js'), 'utf8'));
const i18n = toFactoryBody(await readFile(join(ROOT, 'src', 'i18n.js'), 'utf8'));
const core = toFactoryBody(await readFile(join(ROOT, 'src', 'core.js'), 'utf8'));
const optimize = toFactoryBody(await readFile(join(ROOT, 'src', 'optimize.js'), 'utf8'));
const settingsSource = await readFile(join(ROOT, 'src', 'settings.js'), 'utf8');
const optimizeButtonSource = await readFile(join(ROOT, 'src', 'optimize-button.js'), 'utf8');
const settings = toFactoryBody(settingsSource);
const optimizeButton = toFactoryBody(optimizeButtonSource);
const client = toFactoryBody(await readFile(join(ROOT, 'src', 'client.js'), 'utf8'));


// The wrapper cannot resolve modules; leftover ESM syntax means the strip logic
// (or a source edit) is wrong and the bundle would fail at load time.
if (/^\s*(?:import|export)\s/mu.test(`${protocol}\n${i18nOptimize}\n${i18n}\n${core}\n${optimize}\n${settings}\n${optimizeButton}\n${client}`)) {
  console.error('build-client: unresolved import/export after stripping');
  process.exit(1);
}

const styleTable = STYLE_SOURCES.map(([path, file, name]) => {
  const source = file === 'src/settings.js' ? settingsSource : optimizeButtonSource;
  return `  ${JSON.stringify(path)}: ${JSON.stringify(cssConstant(source, name, file))},`;
}).join('\n');

const bundle = `/* dsh-nonead-prompt-recall client bundle — generated by scripts/build-client.mjs.
 * Edit src/core.js and src/client.js, then run: node scripts/build-client.mjs
 *
 * The __PR_STYLES table below feeds the module meta(). DSH 0.2.2 and newer install
 * those sheets themselves (marking each node with data-plugin / data-path), so
 * the factories' own ensureStyle()/ensureOptimizeStyle() detect that node and
 * skip their manual injection. Older hosts ignore meta entirely and keep the
 * manual path, which is why the constants also stay in the factory sources.
 */
var __PR_STYLES = {
${styleTable}
};

window.__ModuleLoader__.load({
  id: ${JSON.stringify(PLUGIN_ID)},
  meta: () => {
    var stylesheets = {};
    Object.keys(__PR_STYLES).forEach((path) => {
      stylesheets[path] = { text: () => __PR_STYLES[path] };
    });
    return { stylesheets: stylesheets };
  },
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;

${protocol}

${i18nOptimize}

${i18n}

${core}

${optimize}

${settings}

${optimizeButton}

${client}

    module.exports = { name, inject, apply };
    return module.exports;
  }
});
`;

await mkdir(dirname(OUT), { recursive: true });

if (process.argv.includes('--check')) {
  const current = await readFile(OUT, 'utf8').catch(() => '');
  if (current !== bundle) {
    console.error(`${OUT} is out of date; run: node scripts/build-client.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date`);
  process.exit(0);
}

await writeFile(OUT, bundle, 'utf8');
console.log(`built ${OUT} (${bundle.length} bytes)`);
